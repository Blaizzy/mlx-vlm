import numpy as np

_f32 = np.float32


def _fma(a, b, c):
    return _f32(np.float64(a) * np.float64(b) + np.float64(c))


def _pair(a, b=0):
    return _f32(a), _f32(b)


def _norm(x):
    s = x[0] + x[1]
    return s, (x[0] - s) + x[1]


def _add(x, y):
    s = x[0] + y[0]
    return s, ((x[0] - s) + y[0]) + x[1] + y[1]


def _add2(x, y):
    s = x[0] + y[0]
    v = s - x[0]
    t = (x[0] - (s - v)) + (y[0] - v)
    return s, t + (x[1] + y[1])


def _mul(x, y):
    s = x[0] * y[0]
    return s, _fma(x[0], y[1], _fma(x[1], y[0], _fma(x[0], y[0], -s)))


def _mul_scalar(x, y):
    s = x[0] * y
    return s, _fma(x[1], y, _fma(x[0], y, -s))


def _square(x):
    s = x[0] * x[0]
    return s, _fma(x[0] + x[0], x[1], _fma(x[0], x[0], -s))


def _div(n, d):
    t = _f32(1) / d[0]
    s = n[0] * t
    u = _fma(t, n[0], -s)
    v = _fma(-d[1], t, _fma(-d[0], t, _f32(1)))
    return s, _fma(s, v, _fma(n[1], t, u))


def _log(base):
    base = _f32(base)
    e = np.frexp(base * _f32(1 / 0.75))[1] - 1
    m = np.ldexp(base, -e)
    x = _div(_add2(_pair(-1), _pair(m)), _add2(_pair(1), _pair(m)))
    x2 = _square(x)
    t = _f32(0.240320354700088500976562)
    t = _fma(t, x2[0], _f32(0.285112679004669189453125))
    t = _fma(t, x2[0], _f32(0.400007992982864379882812))
    c = _pair(0.66666662693023681640625, 3.69183861259614332084311e-9)
    s = _mul_scalar(_pair(0.69314718246459960938, -1.904654323148236017e-9), _f32(e))
    s = _add(s, (x[0] * _f32(2), x[1] * _f32(2)))
    return _add(s, _mul(_mul(x2, x), _add2(_mul_scalar(x2, t), c)))


def _exp(d):
    q = np.rint((d[0] + d[1]) * _f32(1.442695040888963407359924681001892137))
    s = _add2(d, _pair(q * _f32(-0.693145751953125)))
    s = _add2(s, _pair(q * _f32(-1.428606765330187045e-6)))
    s = _norm(s)
    u = _f32(0.00136324646882712841033936)
    for coefficient in [
        0.00836596917361021041870117,
        0.0416710823774337768554688,
        0.166665524244308471679688,
        0.499999850988388061523438,
    ]:
        u = _fma(u, s[0], _f32(coefficient))
    t = _add(s, _mul_scalar(_square(s), u))
    t = _add(_pair(1), t)
    return np.ldexp(t[0] + t[1], q.astype(np.int32))


def compute_inv_frequencies(base, dims):
    if dims <= 0 or dims % 2:
        raise ValueError("RoPE dimensions must be positive and even")
    base = _f32(base)
    if not np.isfinite(base) or base <= 0:
        raise ValueError("RoPE base must be positive and finite")
    powers = np.arange(0, dims, 2, dtype=np.float32) / _f32(dims)
    # TensorIterator's ARM vector loop handles eight floats per iteration.
    # The remaining elements use scalar powf.
    vector_end = len(powers) // 8 * 8
    frequencies = _f32(1) / np.power(base, powers)
    if (
        vector_end
        and np.finfo(np.float32).tiny <= base < np.finfo(np.float32).max * 0.75
    ):
        frequencies[:vector_end] = _f32(1) / _exp(
            _mul_scalar(_log(base), powers[:vector_end])
        )
    return frequencies
